import {Usuario} from './Usuario.js';
import {Ubicacion} from './Ubicacion.js';
import {Proveedor} from './Proveedor.js';
import {Material} from './Material.js';
import {PoliticaStock} from './PoliticaStock.js';
import {Orden} from './Orden.js';
import {OrdenDetalle} from './OrdenDetalle.js';
import {Movimiento} from './Movimiento.js';
import {Configuracion} from './Configuracion.js';
PoliticaStock.belongsTo(Material,{foreignKey:'material_id',as:'material'});
Material.hasMany(PoliticaStock,{foreignKey:'material_id',as:'politicas'});
PoliticaStock.belongsTo(Ubicacion,{foreignKey:'ubicacion_id',as:'ubicacion'});
Ubicacion.hasMany(PoliticaStock,{foreignKey:'ubicacion_id',as:'politicas'});
Orden.belongsTo(Proveedor,{foreignKey:'proveedor_id',as:'proveedor'});
Proveedor.hasMany(Orden,{foreignKey:'proveedor_id',as:'ordenes'});
Orden.belongsTo(Ubicacion,{foreignKey:'ubicacion_id',as:'ubicacion'});
Ubicacion.hasMany(Orden,{foreignKey:'ubicacion_id',as:'ordenes'});
OrdenDetalle.belongsTo(Orden,{foreignKey:'orden_id',as:'orden'});
Orden.hasMany(OrdenDetalle,{foreignKey:'orden_id',as:'detalles'});
OrdenDetalle.belongsTo(Material,{foreignKey:'material_id',as:'material'});
Material.hasMany(OrdenDetalle,{foreignKey:'material_id',as:'detallesOrden'});
Movimiento.belongsTo(Material,{foreignKey:'material_id',as:'material'});
Material.hasMany(Movimiento,{foreignKey:'material_id',as:'movimientos'});
Movimiento.belongsTo(Usuario,{foreignKey:'usuario_id',as:'usuario'});
Usuario.hasMany(Movimiento,{foreignKey:'usuario_id',as:'movimientos'});
Movimiento.belongsTo(Ubicacion,{foreignKey:'origen_id',as:'origen'});
Ubicacion.hasMany(Movimiento,{foreignKey:'origen_id',as:'movimientosOrigen'});
Movimiento.belongsTo(Ubicacion,{foreignKey:'destino_id',as:'destino'});
Ubicacion.hasMany(Movimiento,{foreignKey:'destino_id',as:'movimientosDestino'});
Movimiento.belongsTo(OrdenDetalle,{foreignKey:'orden_detalle_id',as:'detalleOrden'});
OrdenDetalle.hasMany(Movimiento,{foreignKey:'orden_detalle_id',as:'recepciones'});
export {Usuario,Ubicacion,Proveedor,Material,PoliticaStock,Orden,OrdenDetalle,Movimiento,Configuracion};
